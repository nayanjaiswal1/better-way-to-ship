"use strict";

/** @type {import("@commitlint/types").UserConfig} */
module.exports = {
  extends: ["@commitlint/config-conventional"],

  parserPreset: {
    parserOpts: {
      headerPattern: /^(\w+)(?:\(([^)]*)\))?: (.+)$/,
      headerCorrespondence: ["type", "scope", "subject"],
    },
  },

  plugins: [
    {
      rules: {
        "no-agent-detail": ({ footer }) => {
          if (!footer) return [true];
          const agentPatterns = [
            /co-authored-by:\s*(claude|copilot|chatgpt|gemini|cursor|gpt)/i,
            /generated\s+by\s+(claude|copilot|chatgpt|gemini|cursor|ai|llm)/i,
            /🤖/u,
            /via\s+claude\s+code/i,
            /anthropic/i,
            /openai/i,
          ];
          const matched = agentPatterns.find((re) => re.test(footer));
          if (matched) {
            return [
              false,
              "Commit message must not contain AI agent attribution lines.\n" +
                "Remove any 'Co-authored-by: Claude', 'Generated by ...', or 🤖 lines from the footer.",
            ];
          }
          return [true];
        },
      },
    },
  ],

  rules: {
    // Header
    "header-max-length": [2, "always", 72],
    "header-trim": [2, "always"],

    // Type
    "type-enum": [
      2,
      "always",
      ["feat", "fix", "docs", "style", "refactor", "perf", "test", "build", "ci", "chore", "revert"],
    ],
    "type-case": [2, "always", "lower-case"],
    "type-empty": [2, "never"],

    // Scope (optional, lowercase kebab-case)
    "scope-case": [2, "always", "lower-case"],
    "scope-empty": [0],

    // Subject
    "subject-empty": [2, "never"],
    "subject-full-stop": [2, "never", "."],
    "subject-case": [2, "never", ["sentence-case", "start-case", "pascal-case", "upper-case"]],
    "subject-min-length": [2, "always", 3],
    "subject-max-length": [2, "always", 72],

    // Body
    "body-leading-blank": [2, "always"],
    "body-max-line-length": [2, "always", 100],

    // Footer
    "footer-leading-blank": [2, "always"],
    "footer-max-line-length": [2, "always", 100],

    // Custom: no AI agent attribution
    "no-agent-detail": [2, "always"],
  },
};
